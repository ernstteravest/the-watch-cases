"use client";

import { useActionState } from "react";
import { startMfaEnrollment, verifyMfaCode, type EnrollState, type FormState } from "@/app/beheer/actions/auth";
import { Field, FormAlert, SubmitButton } from "./form";

function CodeField() {
  return (
    <Field
      label="Code uit uw authenticator-app"
      name="code"
      inputMode="numeric"
      autoComplete="one-time-code"
      pattern="\d{6}"
      maxLength={6}
      required
      autoFocus
      className="text-center text-2xl tracking-[0.4em] tabular-nums"
    />
  );
}

/** Signing in: enter the 6-digit code. */
export function MfaCodeForm({ next }: { next: string }) {
  const [state, action] = useActionState<FormState, FormData>(verifyMfaCode, {});
  return (
    <form action={action} className="flex flex-col gap-5" noValidate>
      <input type="hidden" name="next" value={next} />
      <FormAlert error={state.error} />
      <CodeField />
      <SubmitButton pendingText="Controleren…">Bevestigen</SubmitButton>
    </form>
  );
}

function qrSrc(svg: string): string {
  return svg.startsWith("data:") ? svg : `data:image/svg+xml;utf-8,${encodeURIComponent(svg)}`;
}

/** First sign-in: connect an authenticator app, then confirm with a code. */
export function MfaEnrollForm({ next }: { next: string }) {
  const [enroll, start, starting] = useActionState<EnrollState>(startMfaEnrollment, {});
  const [verify, action] = useActionState<FormState, FormData>(verifyMfaCode, {});

  if (!enroll.factorId || !enroll.qrSvg) {
    return (
      <form action={start} className="flex flex-col gap-5">
        <FormAlert error={enroll.error} />
        <ol className="list-decimal space-y-1.5 ps-5 text-[15px] leading-relaxed text-body">
          <li>Installeer een authenticator-app op uw telefoon, bijvoorbeeld Google Authenticator, Microsoft Authenticator of 1Password.</li>
          <li>Klik hieronder op ‘Instellen starten’ en scan de QR-code met de app.</li>
          <li>Vul de code van 6 cijfers in die de app toont.</li>
        </ol>
        <button
          type="submit"
          disabled={starting}
          className="inline-flex min-h-12 w-full cursor-pointer items-center justify-center rounded-pill bg-accent px-7 font-semibold text-paper hover:bg-accent-strong disabled:opacity-60"
        >
          {starting ? "Bezig…" : "Instellen starten"}
        </button>
      </form>
    );
  }

  return (
    <form action={action} className="flex flex-col gap-5" noValidate>
      <input type="hidden" name="next" value={next} />
      <input type="hidden" name="factorId" value={enroll.factorId} />
      {/* eslint-disable-next-line @next/next/no-img-element -- QR code generated by Supabase for this enrolment */}
      <img src={qrSrc(enroll.qrSvg)} alt="QR-code om te scannen met uw authenticator-app" width={200} height={200} className="mx-auto rounded-card border border-line bg-paper p-2" />
      <details className="text-sm text-body">
        <summary className="cursor-pointer font-semibold text-accent">Kunt u niet scannen? Toon de sleutel</summary>
        <p className="mt-2">Voer deze sleutel handmatig in de app in:</p>
        <code className="mt-1 block rounded-card bg-sand p-2 font-mono text-[13px] break-all select-all">{enroll.secret}</code>
      </details>
      <FormAlert error={verify.error} />
      <CodeField />
      <SubmitButton pendingText="Controleren…">Bevestigen en inloggen</SubmitButton>
    </form>
  );
}
